func sqlString(s string) string { return "'" + strings.ReplaceAll(s, "'", "''") + "'" }

func num(f float64) string { return strconv.FormatFloat(f, 'f', -1, 64) }

func borderJSON(b gamedata.BrickBorder) string {
	edge := func(ps []gamedata.BorderPoint) string {
		parts := make([]string, len(ps))
		for i, p := range ps {
			parts[i] = fmt.Sprintf(`{"x":%s,"y":%s}`, num(p.X), num(p.Y))
		}
		return "[" + strings.Join(parts, ",") + "]"
	}
	return fmt.Sprintf(`{"bottom":%s,"right":%s,"top":%s,"left":%s}`, edge(b.Bottom), edge(b.Right), edge(b.Top), edge(b.Left))
}

// SpawnJSON is spawn points as the admin map editor writes them.
func SpawnJSON(sps []gamedata.SpawnPoint) string {
	parts := make([]string, len(sps))
	for i, p := range sps {
		parts[i] = fmt.Sprintf(`{"x":%s,"y":%s}`, num(p.X), num(p.Y))
	}
	return "[" + strings.Join(parts, ",") + "]"
}

func windJSON(w []float64) string { return "[" + num(w[0]) + "," + num(w[1]) + "]" }

// TilesJSON is a tile grid as config_maps.tiles, one row per line.
func TilesJSON(tiles [][]int) string {
	rows := make([]string, len(tiles))
	for i, row := range tiles {
		b, _ := json.Marshal(row)
		rows[i] = string(b)
	}
	return "[\n" + strings.Join(rows, ",\n") + "\n]"
}

// ThemesUpSQL is migration 036: the theme column, the brick types the maps use (fixed ids,
// existing rows kept) and Vietnamese names for the two legacy maps (unless renamed already).
func ThemesUpSQL() string {
	var b strings.Builder
	b.WriteString("-- migrations/036_map_themes.up.sql\n-- " + generatedNote + "\n\n")
	b.WriteString("-- How the client draws a map (gamedata.MapThemes); maps without one keep today's look.\n")
	b.WriteString("ALTER TABLE config_maps ADD COLUMN IF NOT EXISTS theme TEXT NOT NULL DEFAULT 'grassland';\n\n")
	b.WriteString("-- Brick types of the generated maps: the admin seed's 5 defaults (1 Dirt = soft block, 2 Rock =\n")
	b.WriteString("-- hard block) and the soft / hard slope, ceiling, half and plank shapes. Rows that exist are kept.\n")
	b.WriteString("INSERT INTO config_brick_types (brick_type_id, name, image_id, destructible, border, color) VALUES\n")
	bricks := BrickTypes()
	for i, bt := range bricks {
		sep := ","
		if i == len(bricks)-1 {
			sep = ""
		}
		fmt.Fprintf(&b, "    (%d, %s, '', %t, %s, %s)%s\n", bt.BrickTypeID, sqlString(bt.Name), bt.Destructible, sqlString(borderJSON(bt.Border)), sqlString(bt.Color), sep)
	}
	b.WriteString("ON CONFLICT (brick_type_id) DO NOTHING;\n")
	b.WriteString("SELECT setval(pg_get_serial_sequence('config_brick_types', 'brick_type_id'), (SELECT MAX(brick_type_id) FROM config_brick_types));\n\n")
	b.WriteString("-- Vietnamese names (mapName) for the legacy maps, unless an admin renamed them\n")
	for _, m := range legacyMaps {
		fmt.Fprintf(&b, "UPDATE config_maps SET name = %s WHERE map_id = %s AND name = %s;\n", sqlString(m.name), sqlString(m.id), sqlString(m.oldName))
	}
	return b.String()
}

// ThemesDownSQL undoes 036 (the brick shapes go only while they keep their generated names).
func ThemesDownSQL() string {
	var b strings.Builder
	b.WriteString("-- migrations/036_map_themes.down.sql\n-- " + generatedNote + "\n\n")
	for _, m := range legacyMaps {
		fmt.Fprintf(&b, "UPDATE config_maps SET name = %s WHERE map_id = %s AND name = %s;\n", sqlString(m.oldName), sqlString(m.id), sqlString(m.name))
	}
	for _, bt := range BrickTypes() {
		if bt.BrickTypeID < firstShaped {
			continue
		}
		fmt.Fprintf(&b, "DELETE FROM config_brick_types WHERE brick_type_id = %d AND name = %s;\n", bt.BrickTypeID, sqlString(bt.Name))
	}
	b.WriteString("ALTER TABLE config_maps DROP COLUMN IF EXISTS theme;\n")
	return b.String()
}

func mapValues(m gamedata.MapConfig) string {
	return fmt.Sprintf("%s, %s, %s, %d, %d, %d, %d, %d, %s, '[]', %s, %s, %s, %s",
		sqlString(m.MapID), sqlString(m.Name), sqlString(m.Theme), m.Width, m.Height, m.GridWidth, m.GridHeight, m.CellSize,
		sqlString(windJSON(m.DefaultWindPowerRange)), sqlString(SpawnJSON(m.SpawnPoints)), sqlString(TilesJSON(m.Tiles)),
		sqlString(m.Description), sqlString(m.MinRankTier))
}

// MapsUpSQL is migration 037: the 16 generated maps. A new id is inserted once (an admin's edits
// survive reruns); steel_base replaces the legacy row only while that row has no tiles.
func MapsUpSQL() string {
	var b strings.Builder
	b.WriteString("-- migrations/037_battle_maps.up.sql\n-- " + generatedNote + "\n")
	b.WriteString("-- The 16 battle maps (tile grids of config_brick_types ids, 100 x 56 cells of 16 px), editable in\n")
	b.WriteString("-- the admin map editor. A row that exists is kept, so an edited map survives reruns.\n\n")
	cols := "(map_id, name, theme, width, height, grid_width, grid_height, cell_size, default_wind_power_range, terrain_layers, spawn_points, tiles, description, min_rank_tier)"
	for _, m := range Maps() {
		fmt.Fprintf(&b, "-- %s (%s, %s)\n", m.MapID, m.Name, m.Theme)
		fmt.Fprintf(&b, "INSERT INTO config_maps %s\nVALUES (%s)\nON CONFLICT (map_id) DO NOTHING;\n", cols, mapValues(m))
		if m.MapID == "steel_base" {
			fmt.Fprintf(&b, "-- steel_base existed with the legacy terrain: replaced while it still has no tiles\n")
			fmt.Fprintf(&b, "UPDATE config_maps SET (name, theme, width, height, grid_width, grid_height, cell_size, default_wind_power_range, terrain_layers, spawn_points, tiles, description, min_rank_tier, updated_at)\n")
			fmt.Fprintf(&b, "  = (%s, CURRENT_TIMESTAMP)\nWHERE map_id = 'steel_base' AND jsonb_array_length(tiles) = 0;\n", mapValues(m)[len(sqlString(m.MapID))+2:])
		}
		b.WriteString("\n")
	}
	return b.String()
}

// MapsDownSQL undoes 037: the new maps go, steel_base gets its legacy terrain back while it
// still has the generated tiles.
func MapsDownSQL() string {
	var b strings.Builder
	b.WriteString("-- migrations/037_battle_maps.down.sql\n-- " + generatedNote + "\n\n")
	var ids []string
	var steel gamedata.MapConfig
	for _, m := range Maps() {
		if m.MapID == "steel_base" {
			steel = m
			continue
		}
		ids = append(ids, sqlString(m.MapID))
	}
	fmt.Fprintf(&b, "DELETE FROM config_maps WHERE map_id IN (%s);\n\n", strings.Join(ids, ", "))
	b.WriteString("UPDATE config_maps SET name = 'Steel Base', theme = 'grassland', width = 1600, height = 900,\n")
	b.WriteString("    grid_width = 100, grid_height = 56, cell_size = 16, default_wind_power_range = '[0, 2]',\n")
	b.WriteString("    terrain_layers = '[{\"type\":\"lava\",\"hardness\":90,\"yRange\":[700,900]},{\"type\":\"fragile\",\"hardness\":30,\"yRange\":[500,700]}]',\n")
	b.WriteString("    spawn_points = '[{\"x\":250,\"y\":300},{\"x\":1350,\"y\":300},{\"x\":450,\"y\":400},{\"x\":1150,\"y\":400}]',\n")
	b.WriteString("    tiles = '[]', description = '', min_rank_tier = 'gold', updated_at = CURRENT_TIMESTAMP\n")
	fmt.Fprintf(&b, "WHERE map_id = 'steel_base' AND tiles = %s::jsonb;\n", sqlString(TilesJSON(steel.Tiles)))
	return b.String()
}

func yamlString(s string) string {
	b, _ := json.Marshal(s) // a JSON string is a valid YAML double-quoted scalar
	return string(b)
}

// MapsYAML is configs/maps.yaml: the legacy maps and the generated ones, the YAML mirror of
// config_maps the game falls back to (and the tests load).
func MapsYAML() string {
	var b strings.Builder
	b.WriteString("# " + generatedNote + "\n")
	b.WriteString("# config_maps (migrations 036 / 037, edited in the admin map editor) is the source of truth; this file\n")
	b.WriteString("# is its mirror for tests and the YAML fallback. Tiles: rows of configs/bricks.yaml ids, 0 = air.\n")
	for _, m := range legacyMaps {
		fmt.Fprintf(&b, "\n- mapId: %s\n  name: %s\n  theme: grassland\n%s", m.id, yamlString(m.name), m.yaml)
	}
	for _, m := range Maps() {
		fmt.Fprintf(&b, "\n- mapId: %s\n  name: %s\n  theme: %s\n  description: %s\n", m.MapID, yamlString(m.Name), m.Theme, yamlString(m.Description))
		fmt.Fprintf(&b, "  width: %d\n  height: %d\n  gridWidth: %d\n  gridHeight: %d\n  cellSize: %d\n", m.Width, m.Height, m.GridWidth, m.GridHeight, m.CellSize)
		fmt.Fprintf(&b, "  defaultWindPowerRange: %s\n  minRankTier: %s\n  spawnPoints:\n", windJSON(m.DefaultWindPowerRange), m.MinRankTier)
		for _, sp := range m.SpawnPoints {
			fmt.Fprintf(&b, "    - {x: %s, y: %s}\n", num(sp.X), num(sp.Y))
		}
		b.WriteString("  tiles:\n")
		for _, row := range m.Tiles {
			r, _ := json.Marshal(row)
			fmt.Fprintf(&b, "    - %s\n", r)
		}
	}
	return b.String()
}

// BricksYAML is configs/bricks.yaml, the YAML mirror of config_brick_types.
func BricksYAML() string {
	var b strings.Builder
	b.WriteString("# " + generatedNote + "\n")
	b.WriteString("# The YAML mirror of config_brick_types (migration 036). Border points: 0..16, origin bottom left, y up.\n")
	pts := func(ps []gamedata.BorderPoint) string {
		parts := make([]string, len(ps))
		for i, p := range ps {
			parts[i] = fmt.Sprintf("{x: %s, y: %s}", num(p.X), num(p.Y))
		}
		return "[" + strings.Join(parts, ", ") + "]"
	}
	for _, bt := range BrickTypes() {
		fmt.Fprintf(&b, "\n- brickTypeId: %d\n  name: %s\n  destructible: %t\n  color: %s\n", bt.BrickTypeID, yamlString(bt.Name), bt.Destructible, yamlString(bt.Color))
		fmt.Fprintf(&b, "  border:\n    bottom: %s\n    right: %s\n    top: %s\n    left: %s\n", pts(bt.Border.Bottom), pts(bt.Border.Right), pts(bt.Border.Top), pts(bt.Border.Left))
	}
	return b.String()
}
